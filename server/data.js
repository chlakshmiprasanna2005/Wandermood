function makePackage(d) {
  const mood = d.moods[0];
  const itinerary = [
    {
      day: 1,
      title: `Arrive in ${d.name}`,
      details: `Airport pickup from ${d.airportName}, hotel check-in and a relaxed evening walk.`,
    },
  ];
  for (let i = 1; i < d.days - 1; i++) {
    const h = d.highlights[(i - 1) % d.highlights.length];
    itinerary.push({
      day: i + 1,
      title: h,
      details: `Full-day experience: ${h}. Local lunch and free time included.`,
    });
  }
  itinerary.push({
    day: d.days,
    title: "Breakfast and departure",
    details: "Last-minute shopping, then a drop to the airport or station.",
  });
  return {
    id: `pkg-${d.id}`,
    destinationId: d.id,
    title: `${d.name} ${mood} Escape`,
    days: d.days,
    price: d.fromPrice,
    vibes: d.vibes,
    moods: d.moods,
    image: d.image,
    summary: d.blurb,
    itinerary,
    inclusions: [
      "Hotel stay with breakfast",
      "Airport / station transfers",
      "Sightseeing with local guide",
      "All taxes",
    ],
    exclusions: [
      "Flights to and from the destination",
      "Lunch and dinner unless mentioned",
      "Personal expenses",
    ],
  };
}

function makeHotels(d) {
  const h = hash(d.id);
  const tiers = [
    {
      k: "Budget",
      suffix: "Backpackers Inn",
      base: 1500 + (h % 900),
      stars: 3,
      am: ["Free Wi-Fi", "Breakfast"],
    },
    {
      k: "Comfort",
      suffix: "Residency",
      base: 4200 + (h % 1800),
      stars: 4,
      am: ["Free Wi-Fi", "Breakfast", "Pool", "AC"],
    },
    {
      k: "Luxury",
      suffix: "Grand Resort & Spa",
      base: 11000 + (h % 6000),
      stars: 5,
      am: ["Free Wi-Fi", "Breakfast", "Pool", "Spa", "Airport pickup"],
    },
  ];
  return tiers.map((t, i) => ({
    id: `hotel-${d.id}-${i + 1}`,
    destinationId: d.id,
    destinationName: d.name,
    name: `${d.name} ${t.suffix}`,
    tier: t.k,
    stars: t.stars,
    pricePerNight: Math.round(t.base / 100) * 100,
    amenities: t.am,
    rating: +(3.8 + ((h >> (i + 1)) % 12) / 10).toFixed(1),
    image: d.gallery[i + 1],
  }));
}
const hotels = destinations.flatMap(makeHotels);

const AIRLINES = ["IndiGo", "Air India", "Vistara", "Akasa Air", "SpiceJet"];
function searchFlights(from, to, date) {
  if (!AIRPORTS[from] || !AIRPORTS[to] || from === to) return [];
  const base = 2600 + (hash([from, to].sort().join("")) % 6500);
  return AIRLINES.map((airline, i) => {
    const dep = 5 + i * 3 + (hash(from + i) % 2);
    const mins = 70 + (hash(from + to) % 140);
    const arr = dep * 60 + mins;
    const t = (m) =>
      `${String(Math.floor(m / 60) % 24).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`;
    return {
      id: `${from}-${to}-${date}-${i}`,
      airline,
      flightNo: `${airline.slice(0, 2).toUpperCase()}-${100 + (hash(from + to + i) % 800)}`,
      from,
      to,
      fromCity: AIRPORTS[from],
      toCity: AIRPORTS[to],
      date,
      departure: t(dep * 60),
      arrival: t(arr),
      durationMin: mins,
      price: Math.round((base + i * 310 + (hash(date + i) % 700)) / 10) * 10,
    };
  });
}

